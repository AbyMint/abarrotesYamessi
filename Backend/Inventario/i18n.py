def get_translator(lang: str) -> Callable[[str], str]:
    language = lang if lang in TRANSLATIONS else "es"
    selected = TRANSLATIONS[language]
    fallback = TRANSLATIONS["es"]

    def translate(key: str) -> str:
        return selected.get(key, fallback.get(key, key))

    return translate
